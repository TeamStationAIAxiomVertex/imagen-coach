import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

// Measures visible main-content words for every built route against the AGENTS.md budgets.
// Unbudgeted route families are reported without a pass/fail verdict.
const DIST = "dist";
const OUT = "docs/RENDERED_DENSITY_AUDIT.md";

const BUDGETS = [
  { name: "home", match: (r) => r === "/", min: 850, max: 1200 },
  { name: "comparison", match: (r) => r === "/comparaciones" || r.startsWith("/comparaciones/"), min: 650, max: 1100 },
  { name: "publication-hub", match: (r) => r === "/imagen-presencia", min: 450, max: 900 },
  { name: "service", match: (r) => r.startsWith("/servicios-asesoria-de-imagen-coaching"), min: 850, max: 1200 },
  { name: "article", match: (r) => r.startsWith("/imagen-presencia/"), min: null, max: null },
];

async function walk(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...await walk(full));
    else if (entry.name.endsWith(".html")) out.push(full);
  }
  return out;
}

function routeOf(file) {
  const rel = path.relative(DIST, file).replace(/index\.html$/, "").replace(/\.html$/, "").replace(/\/$/, "");
  return rel === "" ? "/" : `/${rel}`;
}

function visibleWords(html) {
  const main = html.match(/<main[\s\S]*?<\/main>/i)?.[0] ?? html;
  return main
    .replace(/<script[\s\S]*?<\/script>/gi, " ")
    .replace(/<style[\s\S]*?<\/style>/gi, " ")
    .replace(/<[^>]+>/g, " ")
    .replace(/&[a-z#0-9]+;/gi, " ")
    .split(/\s+/)
    .filter((word) => /[\p{L}\p{N}]/u.test(word)).length;
}

const files = (await walk(DIST)).filter((file) => !file.endsWith(`${path.sep}404.html`));
const rows = [];
for (const file of files) {
  const route = routeOf(file);
  const words = visibleWords(await readFile(file, "utf8"));
  const budget = BUDGETS.find((item) => item.match(route));
  let verdict = "NOT_BUDGETED";
  if (budget?.min != null) {
    verdict = words < budget.min ? "UNDER" : words > budget.max ? "OVER" : "PASS";
  } else if (budget) {
    verdict = "NO_CAP";
  }
  rows.push({ route, words, family: budget?.name ?? "other", budget, verdict });
}

const count = (verdict) => rows.filter((row) => row.verdict === verdict).length;
const lines = [
  "# Rendered Density Audit",
  "",
  "Generated by `scripts/audit-rendered-density.mjs` from `dist/`. Counts visible words inside `<main>` only.",
  "",
  "Budgets follow `AGENTS.md`: home, service and commercial 850–1200; comparison 650–1100; publication hub 450–900; articles have no cap. Other route families have no written budget and are listed without a verdict.",
  "",
  "## Summary",
  "",
  `- Routes: ${rows.length}`,
  `- PASS: ${count("PASS")}`,
  `- UNDER: ${count("UNDER")}`,
  `- OVER: ${count("OVER")}`,
  `- Articles (no cap): ${count("NO_CAP")}`,
  `- Not budgeted: ${count("NOT_BUDGETED")}`,
  "",
  "## Budgeted routes",
  "",
  "| Route | Family | Words | Budget | Verdict |",
  "| --- | --- | ---: | --- | --- |",
  ...rows
    .filter((row) => row.budget?.min != null)
    .sort((a, b) => a.route.localeCompare(b.route))
    .map((row) => `| ${row.route} | ${row.family} | ${row.words} | ${row.budget.min}–${row.budget.max} | ${row.verdict} |`),
  "",
  "## Not budgeted",
  "",
  "| Route | Words |",
  "| --- | ---: |",
  ...rows
    .filter((row) => row.verdict === "NOT_BUDGETED")
    .sort((a, b) => a.route.localeCompare(b.route))
    .map((row) => `| ${row.route} | ${row.words} |`),
  "",
];

await writeFile(OUT, lines.join("\n"));
console.log(`Wrote ${OUT} for ${rows.length} rendered routes: ${count("UNDER")} under, ${count("OVER")} over.`);
